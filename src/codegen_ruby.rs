/// JSON markers shared by the wrapper and the driver: floats JSON cannot carry, symbols,
/// hashes with non-string keys, and other objects.
const CODEC_RB: &str = r#"
module RustAnythingCodec
  module_function

  def enc(v)
    case v
    when Float
      return { "$num" => "NaN" } if v.nan?
      return { "$num" => v.positive? ? "Infinity" : "-Infinity" } if v.infinite?
      return { "$num" => "-0" } if v.zero? && (1.0 / v).negative?

      v
    when Integer, String, true, false, nil then v
    when Symbol then { "$sym" => v.to_s }
    when Array then v.map { |x| enc(x) }
    when Hash
      if v.keys.all? { |k| k.is_a?(String) }
        v.transform_values { |x| enc(x) }
      else
        { "$hash" => v.map { |k, x| [enc(k), enc(x)] } }
      end
    else
      { "$object" => v.class.name, "value" => v.respond_to?(:to_h) ? enc(v.to_h) : v.inspect }
    end
  end

  def dec(v)
    case v
    when Array then v.map { |x| dec(x) }
    when Hash
      if v.size == 1 && v.key?("$num")
        { "NaN" => Float::NAN, "Infinity" => Float::INFINITY, "-Infinity" => -Float::INFINITY, "-0" => -0.0 }.fetch(v["$num"])
      elsif v.size == 1 && v.key?("$undefined")
        nil
      elsif v.size == 1 && v.key?("$sym")
        v["$sym"].to_sym
      elsif v.size == 1 && v.key?("$hash")
        v["$hash"].to_h { |k, x| [dec(k), dec(x)] }
      else
        v.transform_values { |x| dec(x) }
      end
    else v
    end
  end
end
"#;

/// The wrapper: the same modules and module functions, each calling the Rust library.
pub fn wrapper(m: &Manifest, api: &crate::codegen::PortApi) -> Result<String, String> {
    let lib = m.lib_name();
    let mut out = native(m);
    out.push_str(&module_functions(m, &lib));
    out.push_str(&crate::codegen_batch_native::ruby_wrapper(m, api)?);
    Ok(out)
}

/// The codec and the module that calls the Rust library.
fn native(m: &Manifest) -> String {
    let lib = m.lib_name();
    format!(
        "# frozen_string_literal: true\n\n\
         # The Rust port of `{unit}`, generated by rust-anything: the same module functions, each\n\
         # calling the Rust extension `{lib}_native`. Load it in place of the original files.\n\
         # Regenerate with `rust-anything refresh`.\n\n\
         require_relative \"{lib}_native\"\n",
        unit = m.unit,
    )
}

fn module_functions(m: &Manifest, lib: &str) -> String {
    let mut out = String::new();
    let mut by_module: Vec<(String, Vec<String>)> = Vec::new();
    for f in &m.exports {
        let (recv, name) = receiver(f);
        let sig = signature(f);
        let args: Vec<&str> = f.params.iter().map(|p| p.name.as_str()).collect();
        let def = format!(
            "def {name}({sig})\n  RustAnythingNative{}.{}({})\nend",
            camel(lib),
            f.name,
            args.join(", ")
        );
        match by_module.iter_mut().find(|(r, _)| *r == recv) {
            Some((_, defs)) => defs.push(def),
            None => by_module.push((recv, vec![def])),
        }
    }
    for (recv, defs) in by_module {
        let mut code = reopen(&recv);
        let _ = writeln!(code, "class << {recv}");
        for (i, def) in defs.iter().enumerate() {
            if i > 0 {
                code.push('\n');
            }
            for line in def.lines() {
                let _ = writeln!(code, "  {line}");
            }
        }
        code.push_str("end\n");
        let _ = write!(out, "\n{code}");
    }
    out
}

/// Lines that make each module of `A::B` that is not defined yet, so the wrapper can reopen a
/// receiver that the original made a class (loaded first in replays) as well as a module.
pub(crate) fn reopen(recv: &str) -> String {
    let parts: Vec<&str> = recv.split("::").collect();
    let mut code = String::new();
    for i in 1..=parts.len() {
        let path = parts[..i].join("::");
        let _ = writeln!(code, "module {path}; end unless defined?(::{path})");
    }
    code
}

/// A shadow file: require it after the original. Each module function runs the original and
/// the Rust port, returns the original's result and counts mismatches. `RUST_ANYTHING_MODE=old`
/// runs the original only, `new` the port only.
pub fn shadow(m: &Manifest) -> String {
    let lib = m.lib_name();
    let call = format!("RustAnythingNative{}", camel(&lib));
    let mut out = format!(
        "# frozen_string_literal: true\n\n\
         # Runs `{unit}` and its Rust port side by side. Generated by rust-anything: require it after the\n\
         # original files. RUST_ANYTHING_MODE=old|shadow|new.\n\n\
         require \"json\"\nrequire_relative \"{lib}_native\"\n{CODEC_RB}",
        unit = m.unit,
    );
    out.push_str(
        r#"
module RustAnythingShadow
  MODE = ENV.fetch("RUST_ANYTHING_MODE", "shadow")
  @calls = 0
  @mismatches = 0

  class << self
    attr_reader :calls, :mismatches

    def compare(name, expected, actual)
      @calls += 1
      return if JSON.generate(RustAnythingCodec.enc(expected)) == JSON.generate(RustAnythingCodec.enc(actual))

      @mismatches += 1
      warn "[rust-anything] mismatch in #{name}: expected #{expected.inspect}, got #{actual.inspect}" if @mismatches <= 10
    end
  end
end
"#,
    );
    for f in &m.exports {
        let (recv, name) = receiver(f);
        let sig = signature(f);
        let args: Vec<&str> = f.params.iter().map(|p| p.name.as_str()).collect();
        let args = args.join(", ");
        let _ = write!(
            out,
            "
{recv}.singleton_class.prepend(Module.new do
               def {name}({sig})
                 return {call}.{fname}({args}) if RustAnythingShadow::MODE == \"new\"

                 expected = super
                 unless RustAnythingShadow::MODE == \"old\"
                   actual = begin
        {call}.{fname}({args})
                   rescue StandardError => e
        e
      end
                   RustAnythingShadow.compare(\"{recv}.{name}\", expected, actual)
    end
                 expected
  end
end)
",
            fname = f.name,
        );
    }
    out
}

pub fn camel(lib: &str) -> String {
    lib.split('_')
        .map(|p| {
            let mut c = p.chars();
            c.next()
                .map(|f| f.to_uppercase().chain(c).collect::<String>())
                .unwrap_or_default()
        })
        .collect()
}

/// `{ name: [receiver, method] }` for the driver.
pub fn targets(m: &Manifest) -> serde_json::Value {
    serde_json::Value::Object(
        m.exports
            .iter()
            .map(|f| {
                let (recv, name) = receiver(f);
                (f.name.clone(), serde_json::json!([recv, name]))
            })
            .collect(),
    )
}

pub fn driver() -> String {
    format!("{CODEC_RB}\n{DRIVER_RB}")
}

const DRIVER_RB: &str = r#"
require "json"

mode, targets_path, cases_path, out_path, min_ms, *files = ARGV
files.each { |f| require f }
TARGETS = JSON.parse(File.read(targets_path))

def call(c)
  recv, name = TARGETS.fetch(c["fn"])
  args = (c["args"] || []).dup
  args.pop while args.any? && args.last.is_a?(Hash) && args.last.key?("$undefined")
  args = RustAnythingCodec.dec(args)
  kwargs = RustAnythingCodec.dec(c["kwargs"] || {}).transform_keys(&:to_sym)
  value = Object.const_get(recv).public_send(name, *args, **kwargs)
  { "ok" => RustAnythingCodec.enc(value) }
rescue StandardError, ScriptError => e
  { "error" => e.message, "error_type" => e.class.name }
end

def lines(path)
  File.readlines(path, chomp: true).reject(&:empty?).map { |l| JSON.parse(l) }
end

def same?(expected, got)
  return false if got["error"].to_s.start_with?("Rust panic:")
  return got.key?("error") && expected["error_type"] == got["error_type"] if expected.key?("error")

  !got.key?("error") && JSON.generate(expected["ok"]) == JSON.generate(got["ok"])
end

def wrapper_error(fn_name, wrapper)
  return nil if wrapper.nil? || wrapper.empty?

  recv, name = TARGETS.fetch(fn_name)
  loc = Object.const_get(recv).method(name).source_location&.first
  return nil if loc && File.realpath(loc) == File.realpath(wrapper)

  { "error" => "wrapper did not override #{recv}.#{name} (got #{loc.inspect}, expected #{wrapper.inspect})", "error_type" => "RuntimeError" }
rescue KeyError, NameError, SystemCallError => e
  { "error" => e.message, "error_type" => e.class.name }
end

case mode
when "record"
  progress = ENV["RUST_ANYTHING_PROGRESS"]
  File.open(out_path, "w") do |out|
    JSON.parse(File.read(cases_path)).each_with_index do |c, index|
      File.open(progress, "a") { |p| p.puts(index) } if progress
      line = { "fn" => c["fn"], "args" => c["args"] }
      line["kwargs"] = c["kwargs"] if c["kwargs"]
      line.merge!(call(c))
      begin
        out.puts(JSON.generate(line))
        out.flush
      rescue JSON::GeneratorError, Encoding::UndefinedConversionError
        next
      end
    end
  end
when "diff"
  wrapper = ENV["RUST_ANYTHING_WRAPPER"]
  summary = { "total" => 0, "passed" => 0, "failed" => 0, "missing" => [], "mismatches" => [] }
  lines(cases_path).each do |c|
    summary["total"] += 1
    expected = c.slice("ok", "error", "error_type")
    mismatch = wrapper_error(c["fn"], wrapper)
    got = mismatch || call(c)
    if mismatch.nil? && same?(expected, got)
      summary["passed"] += 1
    else
      summary["failed"] += 1
      shown = c["kwargs"].nil? || c["kwargs"].empty? ? c["args"] : c["args"] + [c["kwargs"]]
      summary["mismatches"] << { "fn" => c["fn"], "args" => shown, "expected" => expected, "actual" => got }
    end
  end
  File.write(out_path, JSON.generate(summary))
when "bench"
  groups = lines(cases_path).group_by { |c| c["fn"] }
  result = {}
  groups.each do |name, cases|
    # Arguments are decoded once, the method looked up once: only the calls are timed.
    recv, meth = TARGETS.fetch(name)
    target = Object.const_get(recv).method(meth)
    prepared = cases.map do |c|
      args = (c["args"] || []).dup
      args.pop while args.any? && args.last.is_a?(Hash) && args.last.key?("$undefined")
      [RustAnythingCodec.dec(args), RustAnythingCodec.dec(c["kwargs"] || {}).transform_keys(&:to_sym)]
    end
    once = lambda do
      prepared.each do |args, kwargs|
        target.call(*args, **kwargs)
      rescue StandardError
        nil
      end
    end
    once.call
    passes = 0
    start = Process.clock_gettime(Process::CLOCK_MONOTONIC)
    loop do
      once.call
      passes += 1
      elapsed = Process.clock_gettime(Process::CLOCK_MONOTONIC) - start
      if elapsed * 1000 >= min_ms.to_i
        result[name] = { "cases" => cases.size, "ns" => elapsed * 1e9 / (passes * cases.size) }
        break
      end
    end
  end
  File.write(out_path, JSON.generate(result))
end
"#;

/// Whether a port type holds `serde_json::Value`: such values convert through `rbconv.rs`;
/// everything else (strings, numbers, booleans, `Vec`, `Option`, `HashMap`) converts directly.
fn via_json(ty: &str) -> bool {
    ty.contains("Value")
}

/// `src/lib.rs` of a Ruby crate: a magnus extension defining `RustAnythingNative<Lib>` with one
/// module function per port function, positional arguments only (the Ruby wrapper keeps the
/// original defaults and keywords).
pub fn lib_rs(m: &Manifest, api: &crate::codegen::PortApi) -> Result<String, String> {
    let lib = m.lib_name();
    let mut out = format!(
        "//! Ruby extension for `{unit}`, generated by rust-anything from `src/port.rs`. Regenerate with\n\
         //! `rust-anything refresh`. Values convert directly between Ruby and Rust: no JSON.\n\n\
         use magnus::{{Error, ExceptionClass, Module, Object, Ruby, function, method, value::ReprValue}};\n\
         #[allow(unused_imports)]\nuse serde_json::Value;\n\n\
         pub mod port;\nmod rbconv;\n\n\
         /// Resolves a `::`-separated constant path like `\"Textkit::ParseError\"` to an `Exception` subclass.\n\
         fn resolve_exception(ruby: &Ruby, kind: &str) -> Option<ExceptionClass> {{\n    \
         let mut parts = kind.split(\"::\").peekable();\n    \
         let mut cur = ruby.class_object().as_value();\n    \
         let mut first = true;\n    \
         while let Some(part) = parts.next() {{\n        \
         if !part.starts_with(|c: char| c.is_ascii_uppercase())\n            \
         || !part.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')\n        \
         {{\n            \
         return None;\n        \
         }}\n        \
         if parts.peek().is_none() {{\n            \
         let class: ExceptionClass = if first {{\n                \
         cur.funcall(\"const_get\", (part,)).ok()?\n            \
         }} else {{\n                \
         cur.funcall(\"const_get\", (part, false)).ok()?\n            \
         }};\n            \
         let exc = ruby\n                \
         .class_object()\n                \
         .const_get::<_, magnus::Value>(\"Exception\")\n                \
         .ok()?;\n            \
         if class.as_value().funcall::<_, _, Option<bool>>(\"<=\", (exc,)).ok().flatten() != Some(true) {{\n                \
         return None;\n            \
         }}\n            \
         return Some(class);\n        \
         }}\n        \
         cur = if first {{\n            \
         first = false;\n            \
         cur.funcall(\"const_get\", (part,)).ok()?\n        \
         }} else {{\n            \
         cur.funcall(\"const_get\", (part, false)).ok()?\n        \
         }};\n        \
         if magnus::RModule::from_value(cur).is_none()\n            \
         && magnus::RClass::from_value(cur).is_none()\n        \
         {{\n            \
         return None;\n        \
         }}\n    \
         }}\n    \
         None\n\
         }}\n\n\
         /// `Err(\"ArgumentError: message\")` raises that exception class; otherwise a RuntimeError.\n\
         fn error(ruby: &Ruby, message: String) -> Error {{\n    \
         if let Some((kind, text)) = message.split_once(\": \")\n        \
         && let Some(class) = resolve_exception(ruby, kind)\n    \
         {{\n        \
         return Error::new(class, text.to_string());\n    \
         }}\n    \
         Error::new(ruby.exception_runtime_error(), message)\n\
         }}\n\n\
         /// Runs the port; a panic becomes a RuntimeError instead of Ruby's uncatchable `fatal`.\n\
         fn guard<T>(ruby: &Ruby, f: impl FnOnce() -> Result<T, String>) -> Result<T, Error> {{\n    \
         match std::panic::catch_unwind(std::panic::AssertUnwindSafe(f)) {{\n        \
         Ok(result) => result.map_err(|m| error(ruby, m)),\n        \
         Err(panic) => {{\n            \
         let text = panic\n                .downcast_ref::<&str>()\n                .map(ToString::to_string)\n                \
         .or_else(|| panic.downcast_ref::<String>().cloned())\n                .unwrap_or_default();\n            \
         Err(Error::new(ruby.exception_runtime_error(), format!(\"Rust panic: {{text}}\")))\n        }}\n    }}\n}}\n",
        unit = m.unit,
    );
    let mut defs = Vec::new();
    for f in &api.functions {
        let params: Vec<String> = f
            .params
            .iter()
            .map(|(n, t)| {
                if via_json(t) {
                    format!("{n}: magnus::Value")
                } else {
                    format!("{n}: {t}")
                }
            })
            .collect();
        let mut body = String::new();
        for (n, t) in f.params.iter().filter(|(_, t)| via_json(t)) {
            let _ = writeln!(
                body,
                "    let {n}: {t} = rbconv::arg({n}).map_err(|m| error(ruby, m))?;"
            );
        }
        let args: Vec<&str> = f.params.iter().map(|(n, _)| n.as_str()).collect();
        let call = format!("port::{}({})", f.rust_name, args.join(", "));
        let call = if f.fallible {
            call
        } else {
            format!("Ok({call})")
        };
        let (ret, tail) = if f.ret == "()" {
            ("()".to_string(), "")
        } else if via_json(&f.ret) {
            (
                "magnus::Value".to_string(),
                "\n        .and_then(|out| rbconv::to_rb(ruby, &out))",
            )
        } else {
            (f.ret.clone(), "")
        };
        let rb_name = format!("rb_{}", f.rust_name.trim_start_matches("r#"));
        let ruby_param = if params.is_empty() {
            "ruby: &Ruby".to_string()
        } else {
            format!("ruby: &Ruby, {}", params.join(", "))
        };
        let _ = writeln!(
            out,
            "\n/// `{js}`.\nfn {rb_name}({ruby_param}) -> Result<{ret}, Error> {{\n{body}    guard(ruby, || {call}){tail}\n}}",
            js = f.js_name,
        );
        defs.push(format!(
            "    native.define_module_function(\"{}\", function!({rb_name}, {}))?;",
            f.js_name,
            f.params.len()
        ));
    }
    let (batches, batch_init) = crate::codegen_batch_native::ruby_rs(m, api)?;
    out.push_str(&batches);
    let _ = writeln!(
        out,
        "\n#[magnus::init(name = \"{lib}_native\")]\nfn init(ruby: &Ruby) -> Result<(), Error> {{\n    \
         let native = ruby.define_module(\"RustAnythingNative{camel}\")?;\n{}\n{batch_init}    Ok(())\n}}",
        defs.join("\n"),
        camel = camel(&lib),
    );
    Ok(out)
}

